GLYPHS = {ch: rows for ch, rows in _R}

# ASCII-латиница -> созвучный кириллический глиф (форма та же)
LATIN_LIKE = {
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "K": "К",
    "M": "М", "O": "О", "P": "Р", "T": "Т", "X": "Х", "Y": "У",
}

# Прочее -> то, что точно нарисовано
ALIASES = {
    "Ё": "Е", "Й": "И", "ё": "Е", "й": "И",
    "—": "-", "–": "-", "−": "-", "«": "<", "»": ">", "№": "N",
    "Х": "Х", "\t": " ",
}

_cache = {}


def glyph(ch):
    ch = ALIASES.get(ch, ch)
    if ch in GLYPHS:
        return GLYPHS[ch]
    up = ch.upper()
    if up in GLYPHS:
        return GLYPHS[up]
    like = LATIN_LIKE.get(up)
    if like:
        return GLYPHS[like]
    return GLYPHS["?"]


def text_width(text):
    return max(0, len(text) * ADV - 1)


def surface(text, color, shadow=None):
    """Готовая Surface с текстом (кэшируется по тексту и цветам)."""
    key = (text, color, shadow)
    s = _cache.get(key)
    if s is None:
        s = pygame.Surface((max(1, text_width(text)), H), pygame.SRCALPHA)
        if shadow is not None:
            _blit_text(s, text, shadow, 0, 0, shadow_off=True)
        _blit_text(s, text, color, 0, 0)
        _cache[key] = s
    return s


def _blit_text(dst, text, color, x0, y0, shadow_off=False):
    for i, ch in enumerate(text):
        rows = glyph(ch)
        ox = x0 + i * ADV
        for ry, row in enumerate(rows):
            for rx, c in enumerate(row):
                if c == "#":
                    px = ox + rx
                    py = y0 + ry
                    if 0 <= px < dst.get_width() and 0 <= py < dst.get_height():
                        dst.set_at((px, py), color)


def draw(dst, text, x, y, color, shadow=None, center=False):
    if center:
        x -= text_width(text) // 2
    if shadow is not None:
        for dx, dy in ((1, 1), (0, 1), (1, 0)):
            dst.blit(surface(text, shadow), (x + dx, y + dy))
    dst.blit(surface(text, color), (x, y))
    return text_width(text)


def plate(dst, rect, bg, edge, text=None, color=None, pad=2):
    """Тёмная плашка с рамкой — чтобы HUD не читался как объект в мире."""
    x, y, w, h = rect
    pygame.draw.rect(dst, bg, (x, y, w, h))
    pygame.draw.rect(dst, edge, (x - 1, y - 1, w + 2, h + 2), 1)
    if text:
        draw(dst, text, x + pad, y + max(1, (h - H) // 2), color)
