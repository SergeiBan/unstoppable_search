# -*- coding: utf-8 -*-
"""Планета: настоящий шар из полигонов.

Мир двумерный, но высота у объектов есть (см. проекцию в render.py), поэтому
шар строится как обычная многогранная фигура: сетка треугольников единичной
сферы, растянутая до радиуса планеты. Дальше всё как со станцией — грани в
координатах камеры, отсечение по ближней плоскости, заливка.

Важное следствие выпуклости: у шара не нужно ни сортировать грани, ни подбирать
силуэт. Достаточно отбросить грани, повёрнутые от камеры, — они всё равно
закрыты передними.

КАК ШАР КЛАДЁТСЯ В КАДР

Грани шара кладутся в круг силуэта радиуса FOCAL*tg(угловой радиус шара), то
есть размер силуэта зависит ТОЛЬКО от расстояния до планеты и не зависит от
курса: при повороте шар едет по кадру, но не раздувается. Перспектива (деление
на глубину) так не умеет: при поле зрения 102 градуса она растягивает предметы к
краю кадра, и шар в 151 клетке от поверхности выходил в лоб 112x112 пикселей, а
в 45 градусах вбок — 108x168 с уехавшим центром. Игрок видит это как «при
повороте планета становится вдвое больше и искажается».

Внутри круга грани расставляются ортогонально (как на глобусе), а глубина у всех
точек одна — 1. Отсюда два следствия: отсечение по ближней плоскости их не
режет (силуэт цел на любом расстоянии), и координаты вершин остаются в пределах
круга (у поверхности это ~1300 пикселей вместо десятков тысяч у перспективы,
которыми SDL мажет мусором).

ПОЧЕМУ СПОСОБ РИСОВАНИЯ ОДИН, А НЕ ДВА

Сначала здесь стояли два способа: круг силуэта вдали и честная перспектива
вплотную, с плавным переходом по угловому радиусу между порогами 40 и 65
градусов. Переход вышел обрывом, а не переходом: ровно на пороге (55,5 клеток
от поверхности) силуэт падал с 211x180 до 17x18, и шар на шаге вперёд резко
уменьшался. Второй способ был и не нужен: у круга радиуса FOCAL*tg(alpha) края
кадра начинают закрываться тогда же, когда их закрывает настоящий шар —
когда угловой радиус доходит до угла на угол кадра (55 градусов, это 22 клетки
до поверхности). Поэтому здесь ровно ОДИН способ рисования: порогов нет, а
вместе с ними нет и скачков размера — ни при повороте, ни при подлёте.

Проверки — в tools/selftest.py («шар при повороте не раздувается», «при подлёте
растёт без скачков»), замеры и кадры — tools/probe_planet.py.
"""

import math

from config import (CANVAS_H, CANVAS_W, C_PLANET, C_PLANET_D, EYE, FOCAL, HZ,
                    PLANET_H, PLANET_LAT, PLANET_LAT_SMALL, PLANET_LIGHT,
                    PLANET_LON, PLANET_LON_SMALL, PLANET_R, PLANET_SIMPLE_AT)


def _norm3(v):
    n = math.sqrt(v[0] * v[0] + v[1] * v[1] + v[2] * v[2]) or 1.0
    return (v[0] / n, v[1] / n, v[2] / n)


def _face_normal(p, q, s):
    """Нормаль треугольника, направленная НАРУЖУ от центра сферы."""
    ux, uy, uz = q[0] - p[0], q[1] - p[1], q[2] - p[2]
    vx, vy, vz = s[0] - p[0], s[1] - p[1], s[2] - p[2]
    nx = uy * vz - uz * vy
    ny = uz * vx - ux * vz
    nz = ux * vy - uy * vx
    ln = math.sqrt(nx * nx + ny * ny + nz * nz)
    if ln < 1e-9:
        return None
    nx, ny, nz = nx / ln, ny / ln, nz / ln
    # у сферы внешняя нормаль совпадает с направлением от центра: выравниваем
    cx = (p[0] + q[0] + s[0]) / 3.0
    cy = (p[1] + q[1] + s[1]) / 3.0
    cz = (p[2] + q[2] + s[2]) / 3.0
    if nx * cx + ny * cy + nz * cz < 0.0:
        nx, ny, nz = -nx, -ny, -nz
    return (nx, ny, nz)


def build_mesh(lat, lon):
    """Треугольники единичной сферы: (три вершины, внешняя нормаль).

    Ось z — высота (полюса сверху и снизу), оси x и y — мировые. Полюсные
    треугольники вырождаются в линию, их выбрасываем сразу.
    """
    rings = []
    for i in range(lat + 1):
        th = math.pi * i / lat                     # 0 — полюс, pi — другой полюс
        hh = math.cos(th)
        rr = math.sin(th)
        ring = []
        for j in range(lon):
            ph = 2.0 * math.pi * j / lon
            ring.append((rr * math.cos(ph), rr * math.sin(ph), hh))
        rings.append(ring)
    tris = []
    for i in range(lat):
        for j in range(lon):
            k = (j + 1) % lon
            a, b = rings[i][j], rings[i][k]
            c, d = rings[i + 1][j], rings[i + 1][k]
            for tri in ((a, b, d), (a, d, c)):
                n = _face_normal(*tri)
                if n is not None:
                    tris.append((tri, n))
    return tris


class Planet:
    """Шар: центр, радиус, сетка граней и отбор лицевых."""

    def __init__(self, cx, cy, radius, h=PLANET_H):
        self.cx, self.cy = float(cx), float(cy)
        self.h = float(h)
        self.r = float(radius)
        self._mesh = {}

    def contains(self, x, y):
        """Внутри ли точка мира тела планеты (по ней и упирается корабль)."""
        dx, dy = x - self.cx, y - self.cy
        return dx * dx + dy * dy <= self.r * self.r

    def dist_to(self, x, y):
        """Расстояние до ПОВЕРХНОСТИ планеты (0 — на поверхности)."""
        dx, dy = x - self.cx, y - self.cy
        return max(0.0, math.hypot(dx, dy) - self.r)

    def mesh(self, lat, lon):
        if (lat, lon) not in self._mesh:
            self._mesh[(lat, lon)] = build_mesh(lat, lon)
        return self._mesh[(lat, lon)]

    def angular(self, cam):
        """Куда смотреть и какой шар большой: (alpha, theta, d, rp, u).

        alpha — угловой радиус шара (asin(r/d)), theta — угол между осью взгляда
        и направлением на центр, d — расстояние до центра, rp — радиус силуэта на
        экране (FOCAL*tg(alpha)), u — единичное направление на центр в осях
        камеры (x — вбок, y — вверх, z — вперёд). Этим и исчерпывается вид шара:
        и размер силуэта, и его место считаются отсюда.
        """
        xc, yc, zc = cam.to_cam(self.cx, self.cy, self.h)
        d2 = xc * xc + yc * yc + zc * zc
        d = math.sqrt(d2)
        if d <= self.r:
            return None                    # камера внутри планеты (не бывает)
        alpha = math.asin(min(1.0, self.r / d))
        theta = math.acos(max(-1.0, min(1.0, zc / d)))
        rp = FOCAL * self.r / math.sqrt(max(d2 - self.r * self.r, 1e-6))
        return (alpha, theta, d, rp, (xc / d, yc / d, zc / d))

    def screen(self, cam):
        """Экранный круг силуэта: (cx, cy, r) или None, если рисовать нечего.

        Радиус круга — FOCAL*tg(угловой радиус шара): ровно тот размер, какой шар
        занимает в лоб, на любом курсе. Центр круга ставим так, чтобы его БЛИЖНИЙ
        к прицелу край встал туда же, куда его ставит касательный луч
        (FOCAL*tg(theta − alpha)): тогда поворот сдвигает шар по кадру и уводит
        его за кромку ровно тогда, когда мимо кромки проходит его поверхность, но
        размера не меняет.
        """
        aff = self.angular(cam)
        if aff is None:
            return None
        alpha, theta, d, rp, u = aff
        # Шар виден, если часть его перед камерой: ближняя точка по оси взгляда
        # стоит u[2]*d + r. Без этой проверки круг рисовался бы и когда планета
        # ровно за спиной.
        if u[2] * d + self.r <= 0.0:
            return None
        # Защита от tg(±90 градусов): ближний край поверхности уходит за камеру.
        # Дальше 88,8 градуса круг всё равно за кадром (тысячи пикселей), так что
        # эта отсечка видна быть не может — она только бережёт от бесконечности.
        near = max(-1.55, min(1.55, theta - alpha))
        rho = FOCAL * (math.tan(near) + math.tan(alpha))
        s = math.hypot(u[0], u[1])
        if s < 1e-9:
            dx, dy = 0.0, 0.0              # смотрим точно в центр шара
        else:
            dx, dy = u[0] / s, -u[1] / s    # куда на экране уезжает центр круга
        return (CANVAS_W * 0.5 + rho * dx, HZ + rho * dy, rp)

    def visible(self, cam):
        """Есть ли шар в кадре: пересекается ли круг силуэта с прямоугольником.

        Считаем по тому самому кругу, который рисуем (и с запасом в пиксель):
        тогда шар не может «щёлкнуть» — пропасть, когда часть его ещё видна, или
        рисоваться, когда видно ноль пикселей. Раньше здесь была проверка по
        углам, и она врала на кромке кадра.
        """
        sc = self.screen(cam)
        if sc is None:
            return False
        cx, cy, r = sc
        return (cx + r >= -1.0 and cx - r <= CANVAS_W + 1.0
                and cy + r >= -1.0 and cy - r <= CANVAS_H + 1.0)

    def faces(self, cam):
        """Лицевые грани в координатах камеры: [(три точки, цвет, обводка), ...].

        Точки приходят в координатах камеры: render.draw_planet проведёт их через
        cam_poly (отсечение по ближней плоскости и перевод на экран). Глубина у
        всех точек одна, поэтому отсечение их не режет, а силуэт остаётся целым.

        Отбор граней: для ортогональной укладки в круг видна ровно та половина
        шара, что обращена к камере (n·c2 > 0), — её проекция и есть круг. Задние
        всё равно закрыты передними, сортировка не нужна.

        Цвет — базовая краска, ослабленная по косинусу угла к источнику света.
        Свет в мировых осях, поэтому терминатор стоит на месте, как бы игрок ни
        разворачивался.
        """
        aff = self.angular(cam)
        sc = self.screen(cam)
        if aff is None or sc is None or not self.visible(cam):
            return []
        alpha, _theta, d, rp, u = aff
        scx, scy, _r = sc
        # Оси в плоскости силуэта, в осях камеры: R̂ — вправо на экране, Û —
        # вверх. Строим их от направления на центр шара так, чтобы û, R̂, Û были
        # правым базисом: тогда грань, чья нормаль смотрит вверх-влево, ложится
        # вверх-влево и на экране, и терминатор не переворачивается.
        rl = math.hypot(u[2], u[0])
        if rl < 1e-9:
            rx, ry, rz = 1.0, 0.0, 0.0      # смотрим ровно в полюс: крен любой
        else:
            rx, ry, rz = u[2] / rl, 0.0, -u[0] / rl
        ux = u[1] * rz - u[2] * ry
        uy = u[2] * rx - u[0] * rz
        uz = u[0] * ry - u[1] * rx
        # направление «от центра шара к камере» в мировых осях — по нему отбираем
        # лицевые грани
        c2x, c2y, c2z = ((cam.x - self.cx) / d, (cam.y - self.cy) / d,
                         (EYE - self.h) / d)
        lat, lon = ((PLANET_LAT, PLANET_LON) if rp >= PLANET_SIMPLE_AT
                    else (PLANET_LAT_SMALL, PLANET_LON_SMALL))
        light = _norm3(PLANET_LIGHT)
        out = []
        for tri, n in self.mesh(lat, lon):
            if n[0] * c2x + n[1] * c2y + n[2] * c2z <= 0.0:
                continue
            dl = n[0] * light[0] + n[1] * light[1] + n[2] * light[2]
            # Разброс яркости широкий (от 15% до 100%): при узком шар выглядел
            # однотонным, объём не читался.
            k = 0.15 + 0.85 * max(0.0, dl) ** 0.8
            col = tuple(int(C_PLANET_D[i] + (C_PLANET[i] - C_PLANET_D[i]) * k)
                        for i in range(3))
            # Обводка темнее заливки: она и закрывает волосяные щели между
            # гранями, и показывает саму многогранную структуру шара.
            edge = tuple(int(c * 0.72) for c in col)
            pts = []
            for v in tri:
                # Вершина единичной сферы в осях камеры: поворот на курс; высота
                # остаётся мировой осью z, поэтому полюса шара смотрят вверх мира.
                vr = v[0] * cam.ca - v[1] * cam.sa
                vu = v[2]
                vf = v[0] * cam.sa + v[1] * cam.ca
                ox = rp * (vr * rx + vu * ry + vf * rz)     # вправо, пикселей
                oy = rp * (vr * ux + vu * uy + vf * uz)     # вверх, пикселей
                # Из пикселей обратно в координаты камеры: глубина 1, поэтому
                # cam.to_screen вернёт ровно эти же пиксели.
                pts.append(((scx + ox - CANVAS_W * 0.5) / FOCAL,
                            (HZ - scy + oy) / FOCAL, 1.0))
            out.append((pts, col, edge))
        return out


def make_planet(world):
    """Планета к югу от станции: центр в 500 клетках от её кромки, радиус 100."""
    from config import PLANET_DIST, PLANET_R
    return Planet(world.cx, world.sy0 - PLANET_DIST, PLANET_R)
